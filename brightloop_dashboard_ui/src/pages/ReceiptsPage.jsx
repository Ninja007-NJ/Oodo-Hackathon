// ReceiptsPage.jsx - Dedicated Tax Receipt Verification & Printable Receipts Center
import React, { useState, useEffect } from 'react';
import {
  Receipt,
  Search,
  Filter,
  CheckCircle2,
  Printer,
  Download,
  Share2,
  Copy,
  ShieldCheck,
  Building2,
  ExternalLink,
  QrCode,
  ArrowRight,
  Check,
  X
} from 'lucide-react';

export default function ReceiptsPage({
  receipts,
  activeReceiptId,
  onNavigate,
}) {
  const [search, setSearch] = useState('');
  const [selectedReceipt, setSelectedReceipt] = useState(null);
  const [copiedHash, setCopiedHash] = useState(false);
  const [downloadSuccess, setDownloadSuccess] = useState(false);

  // If passed an activeReceiptId from invoice or payment view, auto-open that receipt
  useEffect(() => {
    if (activeReceiptId) {
      const match = receipts.find((r) => r.receiptNumber === activeReceiptId || r.id === activeReceiptId);
      if (match) setSelectedReceipt(match);
    }
  }, [activeReceiptId, receipts]);

  const filtered = receipts.filter((r) => {
    if (!search) return true;
    const q = search.toLowerCase();
    return (
      r.receiptNumber.toLowerCase().includes(q) ||
      r.invoiceNumber.toLowerCase().includes(q) ||
      r.customerName.toLowerCase().includes(q) ||
      r.transactionId.toLowerCase().includes(q)
    );
  });

  const handleCopyHash = (hash) => {
    navigator.clipboard?.writeText(hash);
    setCopiedHash(true);
    setTimeout(() => setCopiedHash(false), 2500);
  };

  const handleSimulateDownload = (r) => {
    setDownloadSuccess(true);
    setTimeout(() => setDownloadSuccess(false), 3000);
  };

  return (
    <main className="max-w-7xl mx-auto p-4 sm:p-6 lg:p-8 space-y-6">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-slate-800 pb-5">
        <div>
          <div className="flex items-center gap-2">
            <span className="text-[10px] font-bold uppercase tracking-wider text-emerald-400 bg-emerald-950/60 px-2.5 py-0.5 rounded-full border border-emerald-800/50">
              Module 5 • Verified GST Receipts
            </span>
            <span className="text-xs text-slate-400">Cryptographically Signed Tax Invoices</span>
          </div>
          <h1 className="text-2xl font-black text-white mt-1.5 flex items-center gap-2">
            <Receipt className="w-6 h-6 text-emerald-400" />
            Payment Receipts &amp; Verification Center
          </h1>
          <p className="text-xs text-slate-400 mt-1">
            Official tax-compliant payment acknowledgments with 18% GST (CGST+SGST) itemization, tokenized transaction hashes, and print-ready formats.
          </p>
        </div>

        {/* Shortcuts */}
        <div className="flex items-center gap-2">
          {onNavigate && (
            <>
              <button
                onClick={() => onNavigate('invoices')}
                className="px-3.5 py-2 rounded-xl bg-slate-900 border border-slate-700 hover:border-cyan-500/50 text-cyan-300 text-xs font-bold transition-all flex items-center gap-1.5 cursor-pointer"
              >
                <span>Invoices</span>
                <ArrowRight className="w-3.5 h-3.5" />
              </button>
              <button
                onClick={() => onNavigate('payments')}
                className="px-3.5 py-2 rounded-xl bg-slate-900 border border-slate-700 hover:border-cyan-500/50 text-cyan-300 text-xs font-bold transition-all flex items-center gap-1.5 cursor-pointer"
              >
                <span>Payments Ledger</span>
                <ArrowRight className="w-3.5 h-3.5" />
              </button>
            </>
          )}
        </div>
      </div>

      {/* Security & Verification Banner */}
      <div className="p-4 rounded-2xl bg-emerald-950/30 border border-emerald-800/60 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-emerald-900/60 border border-emerald-600 text-emerald-300 flex items-center justify-center shrink-0">
            <ShieldCheck className="w-6 h-6" />
          </div>
          <div>
            <div className="text-xs font-bold text-white flex items-center gap-2">
              <span>Authenticity Verification Active</span>
              <span className="text-[10px] font-bold text-emerald-400 bg-emerald-950 px-2 py-0.5 rounded-full border border-emerald-800">
                SHA-256 Signed
              </span>
            </div>
            <div className="text-[11px] text-slate-300 mt-0.5">
              Every receipt generated by Brightloop embeds a non-tamperable cryptographic signature and compliance breakdown for Indian GST law.
            </div>
          </div>
        </div>
        <div className="text-right shrink-0">
          <div className="text-[10px] text-slate-400">Company GSTIN</div>
          <div className="font-mono font-bold text-emerald-400 text-xs">29AABCB1234C1Z5</div>
        </div>
      </div>

      {/* Search Bar */}
      <div className="flex items-center justify-between bg-slate-900/80 p-3 rounded-2xl border border-slate-800">
        <div className="relative w-full max-w-md">
          <Search className="w-3.5 h-3.5 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search receipt #, invoice #, customer name, transaction..."
            className="w-full bg-slate-950 border border-slate-800 rounded-xl pl-8 pr-3 py-1.5 text-xs text-slate-200 placeholder-slate-500 focus:outline-none focus:border-emerald-500"
          />
        </div>
        <div className="text-xs text-slate-400 font-mono">
          Showing {filtered.length} of {receipts.length} verified receipts
        </div>
      </div>

      {/* Receipts Table */}
      <div className="rounded-3xl border border-slate-800 bg-slate-900/90 overflow-hidden shadow-xl backdrop-blur-xl">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-950/80 border-b border-slate-800 text-slate-400 font-bold uppercase text-[10px] tracking-wider">
              <tr>
                <th className="py-3.5 px-4">Receipt #</th>
                <th className="py-3.5 px-4">Origin Invoice</th>
                <th className="py-3.5 px-4">Issue Date</th>
                <th className="py-3.5 px-4">Billed Customer</th>
                <th className="py-3.5 px-4">Payment Method Rail</th>
                <th className="py-3.5 px-4 text-center">Status</th>
                <th className="py-3.5 px-4 text-right">Settled Total</th>
                <th className="py-3.5 px-4 text-center">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60">
              {filtered.map((rcp) => (
                <tr key={rcp.id} className="hover:bg-slate-800/40 transition-colors">
                  <td className="py-3.5 px-4 font-mono font-bold text-emerald-400">
                    <button
                      onClick={() => setSelectedReceipt(rcp)}
                      className="hover:underline cursor-pointer flex items-center gap-1.5"
                    >
                      <Receipt className="w-3.5 h-3.5 text-emerald-400" />
                      {rcp.receiptNumber}
                    </button>
                  </td>
                  <td className="py-3.5 px-4 font-mono text-cyan-300">{rcp.invoiceNumber}</td>
                  <td className="py-3.5 px-4 text-slate-400 font-mono">{rcp.issueDate}</td>
                  <td className="py-3.5 px-4 font-medium text-slate-200">
                    <div>{rcp.customerName}</div>
                    <div className="text-[10px] text-slate-500">GST: {rcp.customerGst}</div>
                  </td>
                  <td className="py-3.5 px-4 text-slate-300">{rcp.paymentMethod}</td>
                  <td className="py-3.5 px-4 text-center">
                    <span className="inline-block px-2.5 py-0.5 rounded-full text-[10px] font-bold border uppercase tracking-wide bg-emerald-950/80 text-emerald-400 border-emerald-800/60">
                      {rcp.status}
                    </span>
                  </td>
                  <td className="py-3.5 px-4 text-right font-black text-white">
                    ₹{rcp.amountTotal.toLocaleString('en-IN')}
                  </td>
                  <td className="py-3.5 px-4 text-center">
                    <div className="flex items-center justify-center gap-2">
                      <button
                        onClick={() => setSelectedReceipt(rcp)}
                        className="px-3 py-1 rounded-xl bg-emerald-500 text-slate-950 hover:bg-emerald-400 text-[11px] font-bold shadow-md shadow-emerald-500/20 transition-all cursor-pointer flex items-center gap-1"
                      >
                        <Printer className="w-3 h-3" />
                        <span>View &amp; Print</span>
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
              {filtered.length === 0 && (
                <tr>
                  <td colSpan={8} className="text-center py-10 text-slate-500">
                    No receipt records found matching your query.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Official Tax Receipt Modal with Printable Document Template */}
      {selectedReceipt && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 backdrop-blur-xs p-4 overflow-y-auto">
          <div className="w-full max-w-2xl bg-white text-slate-900 rounded-3xl p-6 sm:p-8 shadow-2xl space-y-6 my-auto animate-in zoom-in-95 duration-200 relative border-2 border-emerald-600/30">
            {/* Top Close Button */}
            <button
              onClick={() => setSelectedReceipt(null)}
              className="absolute top-4 right-4 p-1.5 rounded-full bg-slate-100 hover:bg-slate-200 text-slate-500 hover:text-slate-800 transition-colors cursor-pointer"
            >
              <X className="w-5 h-5" />
            </button>

            {/* Official Header */}
            <div className="flex flex-col sm:flex-row justify-between items-start gap-4 border-b border-slate-200 pb-5">
              <div>
                <div className="flex items-center gap-2">
                  <div className="w-7 h-7 rounded-lg bg-emerald-600 text-white flex items-center justify-center font-black text-sm">
                    BL
                  </div>
                  <span className="text-xl font-black tracking-tight text-slate-900">
                    BRIGHTLOOP TECHNOLOGIES
                  </span>
                </div>
                <div className="text-[11px] text-slate-600 mt-1 max-w-xs leading-relaxed">
                  Level 4, Orion Business Tower, MG Road, Bengaluru, KA 560001
                </div>
                <div className="text-[11px] font-mono text-slate-700 mt-0.5">
                  GSTIN: <strong>29AABCB1234C1Z5</strong> • PAN: <strong>AABCB1234C</strong>
                </div>
              </div>

              {/* Verified Stamp Badge */}
              <div className="border-2 border-emerald-600 rounded-2xl p-2.5 bg-emerald-50 text-emerald-900 text-center transform sm:rotate-2 shrink-0">
                <div className="text-[9px] font-black tracking-wider uppercase flex items-center justify-center gap-1 text-emerald-700">
                  <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
                  Verified Tax Receipt
                </div>
                <div className="text-xs font-black text-emerald-950 mt-0.5">PAYMENT SETTLED</div>
                <div className="text-[9px] font-mono text-emerald-700 mt-0.5">{selectedReceipt.receiptNumber}</div>
              </div>
            </div>

            {/* Payer and Receipt Metadata */}
            <div className="grid grid-cols-2 gap-4 text-xs bg-slate-50 p-4 rounded-2xl border border-slate-200">
              <div>
                <span className="text-[10px] uppercase font-bold text-slate-400 block mb-0.5">Billed Payer</span>
                <div className="font-bold text-slate-900 text-sm">{selectedReceipt.customerName}</div>
                <div className="text-slate-600 text-[11px] mt-0.5">{selectedReceipt.billingAddress}</div>
                <div className="text-slate-700 text-[11px] font-mono mt-1">
                  Customer GSTIN: <strong>{selectedReceipt.customerGst}</strong>
                </div>
              </div>

              <div className="space-y-1 font-mono text-right">
                <div>
                  <span className="text-slate-400 font-sans text-[10px] uppercase font-bold">Receipt Date: </span>
                  <span className="font-bold text-slate-800">{selectedReceipt.issueDate}</span>
                </div>
                <div>
                  <span className="text-slate-400 font-sans text-[10px] uppercase font-bold">Invoice Ref: </span>
                  <span className="font-bold text-cyan-700">{selectedReceipt.invoiceNumber}</span>
                </div>
                <div>
                  <span className="text-slate-400 font-sans text-[10px] uppercase font-bold">Payment Rail: </span>
                  <span className="text-slate-700">{selectedReceipt.paymentMethod}</span>
                </div>
                <div>
                  <span className="text-slate-400 font-sans text-[10px] uppercase font-bold">Txn Ref: </span>
                  <span className="text-slate-600 text-[10px]">{selectedReceipt.transactionId}</span>
                </div>
              </div>
            </div>

            {/* Items Table */}
            <div className="border border-slate-200 rounded-xl overflow-hidden">
              <table className="w-full text-xs text-left">
                <thead className="bg-slate-100 text-slate-600 font-bold uppercase text-[10px]">
                  <tr>
                    <th className="py-2.5 px-3">Description</th>
                    <th className="py-2.5 px-3 text-center">Qty</th>
                    <th className="py-2.5 px-3 text-right">Rate</th>
                    <th className="py-2.5 px-3 text-right">Tax (18%)</th>
                    <th className="py-2.5 px-3 text-right">Total</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {selectedReceipt.lines && selectedReceipt.lines.length > 0 ? (
                    selectedReceipt.lines.map((item, idx) => (
                      <tr key={idx}>
                        <td className="py-2 px-3 font-medium text-slate-800">{item.description}</td>
                        <td className="py-2 px-3 text-center text-slate-600">{item.qty}</td>
                        <td className="py-2 px-3 text-right font-mono text-slate-700">₹{item.unitPrice}</td>
                        <td className="py-2 px-3 text-right font-mono text-slate-500">18% GST</td>
                        <td className="py-2 px-3 text-right font-mono font-bold text-slate-900">₹{item.total}</td>
                      </tr>
                    ))
                  ) : (
                    <tr>
                      <td className="py-2 px-3 font-medium text-slate-800">Brightloop Subscription Service</td>
                      <td className="py-2 px-3 text-center text-slate-600">1</td>
                      <td className="py-2 px-3 text-right font-mono text-slate-700">₹{selectedReceipt.amountUntaxed}</td>
                      <td className="py-2 px-3 text-right font-mono text-slate-500">18% GST</td>
                      <td className="py-2 px-3 text-right font-mono font-bold text-slate-900">₹{selectedReceipt.amountUntaxed}</td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>

            {/* Tax Computation & Grand Total */}
            <div className="flex flex-col sm:flex-row justify-between items-start sm:items-end gap-3 pt-1">
              <div className="text-[11px] text-slate-500 max-w-xs">
                <div className="font-bold text-slate-700">Amount in Words:</div>
                <div className="italic text-slate-600">
                  Three Thousand Twenty Indian Rupees and Eighty Paise Only.
                </div>
              </div>

              <div className="w-full sm:w-64 space-y-1 text-xs font-mono">
                <div className="flex justify-between text-slate-600">
                  <span>Untaxed Subtotal:</span>
                  <span>₹{selectedReceipt.amountUntaxed.toFixed(2)}</span>
                </div>
                <div className="flex justify-between text-slate-600">
                  <span>CGST (9%):</span>
                  <span>₹{selectedReceipt.cgstAmount.toFixed(2)}</span>
                </div>
                <div className="flex justify-between text-slate-600">
                  <span>SGST (9%):</span>
                  <span>₹{selectedReceipt.sgstAmount.toFixed(2)}</span>
                </div>
                <div className="flex justify-between text-sm font-black text-slate-900 border-t border-slate-300 pt-1.5">
                  <span>Total Settled:</span>
                  <span className="text-emerald-700">₹{selectedReceipt.amountTotal.toFixed(2)}</span>
                </div>
              </div>
            </div>

            {/* Cryptographic SHA-256 Hash Footnote */}
            <div className="p-3 bg-slate-50 border border-slate-200 rounded-xl text-[10px] flex items-center justify-between text-slate-500 font-mono">
              <div className="truncate mr-2">
                Digital Signature: <span className="text-slate-700">{selectedReceipt.verificationHash}</span>
              </div>
              <button
                onClick={() => handleCopyHash(selectedReceipt.verificationHash)}
                className="shrink-0 text-slate-600 hover:text-slate-900 flex items-center gap-1 font-sans font-bold cursor-pointer"
              >
                {copiedHash ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
                <span>{copiedHash ? 'Copied' : 'Copy'}</span>
              </button>
            </div>

            {/* Print and Download Actions */}
            <div className="flex items-center justify-between border-t border-slate-200 pt-4">
              <div className="flex items-center gap-2">
                <button
                  onClick={() => window.print()}
                  className="px-4 py-2 rounded-xl bg-slate-900 hover:bg-slate-800 text-white text-xs font-bold flex items-center gap-1.5 shadow-md cursor-pointer"
                >
                  <Printer className="w-3.5 h-3.5 text-cyan-400" />
                  <span>Print Receipt</span>
                </button>
                <button
                  onClick={() => handleSimulateDownload(selectedReceipt)}
                  className="px-4 py-2 rounded-xl border border-slate-300 hover:bg-slate-100 text-slate-800 text-xs font-bold flex items-center gap-1.5 cursor-pointer"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>{downloadSuccess ? 'Downloaded!' : 'Download PDF'}</span>
                </button>
              </div>

              <button
                onClick={() => setSelectedReceipt(null)}
                className="px-4 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-bold cursor-pointer"
              >
                Done
              </button>
            </div>
          </div>
        </div>
      )}
    </main>
  );
}

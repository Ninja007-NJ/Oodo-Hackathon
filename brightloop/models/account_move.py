# -*- coding: utf-8 -*-
from odoo import models, fields


class AccountMove(models.Model):
    _inherit = 'account.move'

    subscription_id = fields.Many2one(
        'brightloop.subscription',
        string='Originating Subscription',
        index=True,
        ondelete='set null',
        copy=False
    )
    billing_job = fields.Boolean(
        string='Created by Billing Job',
        default=False,
        index=True,
        copy=False,
        help='Flag indicating if this invoice was automatically generated by the Brightloop recurring billing engine.'
    )


class AccountMoveLine(models.Model):
    _inherit = 'account.move.line'

    brightloop_discount_name = fields.Char(
        string='Applied Discount',
        copy=False,
        help='Name of the promotional discount applied to this invoice line.'
    )
